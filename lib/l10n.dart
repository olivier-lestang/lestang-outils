class Translator {
  final String language;
  Translator(this.language);
  String t(String key) =>
      _glossaires[language]?[key] ?? _glossaires['fr']![key] ?? key;

  /* the translator is used like a function : trad ( 'key' ) */
  String call(String key) => t(key);
}
