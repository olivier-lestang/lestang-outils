class Traducteur {
  final String langue;
  Traducteur(this.langue);
  String t(String cle) =>
      _glossaires[langue]?[cle] ?? _glossaires['fr']![cle] ?? cle;

  /* le traducteur s emploie comme une fonction : trad ( 'cle' ) */
  String call(String cle) => t(cle);
}
