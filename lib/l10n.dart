import 'dart:ui' as ui;

const uiLanguages = ['fr', 'en', 'es', 'pt', 'it', 'de', 'zh-Hans', 'zh-Hant'];

/* the written Chinese follows the script of the system: traditional
   for Taiwan, Hong Kong and Macau, simplified elsewhere */
String systemLanguage() {
  final l = ui.PlatformDispatcher.instance.locale;
  if (l.languageCode == 'zh') {
    return l.scriptCode == 'Hant' ||
            l.countryCode == 'TW' ||
            l.countryCode == 'HK' ||
            l.countryCode == 'MO'
        ? 'zh-Hant'
        : 'zh-Hans';
  }
  return uiLanguages.contains(l.languageCode) ? l.languageCode : 'fr';
}

